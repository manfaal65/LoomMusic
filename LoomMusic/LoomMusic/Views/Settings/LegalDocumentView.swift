import SwiftUI

enum LegalDocumentType: String, Identifiable {
    case privacyPolicy = "Privacy Policy"
    case termsOfService = "Terms of Service"

    var id: String { rawValue }

    var title: String { rawValue }

    var webURL: URL? {
        switch self {
        case .privacyPolicy:
            return URL(string: "https://sites.google.com/view/aamirsohail/privacy-policy")
        case .termsOfService:
            return URL(string: "https://sites.google.com/view/aamirsohail/terms-of-use")
        }
    }

    var content: String {
        switch self {
        case .privacyPolicy:
            return """
            Last updated: October 2026

            1. Overview
            YuTUNES ("we", "our", or "the app") is committed to protecting your privacy. This Privacy Policy explains our practices regarding data collection and usage when you use the YuTUNES macOS application.

            2. Local Audio & Personal Media
            Your audio files, playlists, and playback history remain strictly on your local device. We do not copy, upload, or transmit your local audio files to any remote servers.

            3. AI Companion Features
            When you use the AI Lyrics Generator or AI Song Summary features, your requested prompts or song metadata are processed securely via our AI backend (Google Gemini) solely to generate the requested lyrics or summary. This data is not used for advertising or persistent tracking.

            4. In-App Purchases & Subscriptions
            All subscription and in-app purchase transactions are handled directly through Apple's App Store and StoreKit. We do not collect or store your payment details or credit card information.

            5. Analytics & Diagnostics
            We may collect anonymous crash logs and diagnostic information via Firebase Crashlytics to fix bugs and improve performance. No personally identifiable audio information is collected.

            6. Contact & Inquiries
            For any questions or inquiries regarding this Privacy Policy, please contact us at aamir.soh87@gmail.com or visit our policy website at https://sites.google.com/view/aamirsohail/privacy-policy.
            """

        case .termsOfService:
            return """
            Last updated: October 2026

            1. Acceptance of Terms
            By downloading, installing, or using YuTUNES, you agree to be bound by these Terms of Service. If you do not agree, do not use the application.

            2. License & Personal Use
            YuTUNES grants you a personal, non-exclusive, non-transferable license to use the app on your Apple devices for personal entertainment. You are responsible for ensuring that any audio files you import comply with applicable copyright laws.

            3. Subscriptions & Billing
            YuTUNES Pro offers optional auto-renewing subscriptions and lifetime access options. Payment will be charged to your Apple ID account upon purchase confirmation. Subscriptions automatically renew unless cancelled at least 24 hours before the end of the current billing cycle via your Apple Account Settings.

            4. AI Features Disclaimer
            AI-generated lyrics and song summaries are generated by automated machine learning models. Content is provided for entertainment purposes, and we do not guarantee factual accuracy or copyright clearance for generated text.

            5. Limitation of Liability
            YuTUNES is provided on an "as is" and "as available" basis without warranties of any kind. Under no circumstances shall the developers be liable for direct, indirect, or incidental damages resulting from the use of the app.

            6. Governing Law
            These terms are governed by and construed in accordance with the laws applicable to Apple App Store software distribution.
            """
        }
    }
}

struct LegalDocumentView: View {
    let documentType: LegalDocumentType
    @Environment(\.dismiss) private var dismiss

    var body: some View {
        VStack(spacing: 0) {
            header

            Divider()
                .background(Color.loomDivider)

            ScrollView {
                VStack(alignment: .leading, spacing: 16) {
                    Text(documentType.content)
                        .font(.system(size: 13))
                        .lineSpacing(5)
                        .foregroundStyle(Color.loomTextSecondary)
                        .frame(maxWidth: .infinity, alignment: .leading)
                }
                .padding(24)
            }

            if let url = documentType.webURL {
                Divider()
                    .background(Color.loomDivider)

                HStack {
                    Spacer()
                    Button(action: { NSWorkspace.shared.open(url) }) {
                        HStack(spacing: 6) {
                            Text("Open in Browser")
                            Image(systemName: "arrow.up.right")
                                .font(.system(size: 11))
                        }
                        .font(.system(size: 12, weight: .medium))
                        .foregroundStyle(Color.loomAccentBlue)
                    }
                    .buttonStyle(.plain)
                }
                .padding(.horizontal, 24)
                .padding(.vertical, 14)
            }
        }
        .frame(width: 540, height: 500)
        .background(Color.loomBackground)
    }

    private var header: some View {
        HStack {
            Text(documentType.title)
                .font(.system(size: 18, weight: .bold))
                .foregroundStyle(.white)

            Spacer()

            Button(action: { dismiss() }) {
                Image(systemName: "xmark")
                    .font(.system(size: 12, weight: .semibold))
                    .foregroundStyle(.white)
                    .frame(width: 28, height: 28)
                    .background(Circle().fill(Color.white.opacity(0.1)))
            }
            .buttonStyle(.plain)
        }
        .padding(.horizontal, 24)
        .padding(.vertical, 18)
    }
}

